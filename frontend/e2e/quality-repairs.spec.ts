import {expect,test} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
test('preview, approve and reverse a real derived correction while originals remain identical',async({page,request})=>{
 const python=process.env.SHEETPILOT_PYTHON||path.resolve('../.venv/Scripts/python.exe');
 const content=execFileSync(python,['-c',"from openpyxl import Workbook; from io import BytesIO; import sys; b=Workbook(); s=b.active; s.title='Sales'; s.append(['Order ID','SKU','Quantity','Unit price','Date','Currency']); [s.append(r) for r in [('O1','A','1,200',2,'04/11/2026','USD'),('O2','A',3,2,'2026-11-04','USD'),('O3','A',4,2,'bad','USD')]]; o=BytesIO(); b.save(o); sys.stdout.buffer.write(o.getvalue())"]);
 const workspace=(await (await request.post('/api/workspaces',{data:{name:'Fictional corrections'}})).json()).id;
 const base='/api/workspaces/'+workspace;
 const book=await (await request.post(base+'/uploads',{multipart:{file:{name:'Ambiguous.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:content}}})).json();
 const table=(await (await request.get(base+'/state')).json()).tables[0];
 expect((await request.put(base+'/tables/'+table.id,{data:{entity:'sales',fields:{'1':'order_id','2':'product_id','3':'quantity','4':'unit_price','5':'sale_date','6':'currency'},header_row:1,expected_revision:0}})).ok()).toBe(true);
 const initial=await (await request.get(base+'/quality/repairs')).json();const issue=initial.issues.find((q:any)=>q.row===2);
 await page.addInitScript(id=>localStorage.setItem('sheetpilot-workspace',id),workspace);
 await page.goto('/quality#issue-'+issue.id);
 const card=page.locator('#issue-'+issue.id);
 await card.getByLabel('Source cell for '+issue.id).selectOption('3');
 await card.getByLabel('Interpretation for '+issue.id).selectOption('thousands_comma');
 await card.getByRole('button',{name:'Preview correction',exact:true}).click();
 const preview=page.getByRole('region',{name:'Correction preview'});
 await expect(preview).toContainText('2414.00');
 expect((await (await request.get(base+'/dashboard')).json()).revenue[0].amount).toBe('14.00');
 await expect(preview.getByRole('button',{name:'Approve correction'})).toBeDisabled();
 await preview.getByRole('checkbox').check();await preview.getByRole('button',{name:'Approve correction'}).click();
 await expect(page.getByText('Correction revision 1',{exact:true})).toBeVisible();
 expect((await (await request.get(base+'/dashboard')).json()).revenue[0].amount).toBe('2414.00');
 await page.getByRole('button',{name:'Preview reversal · revision 1'}).click();
 await expect(preview).toContainText('Reversal preview');
 await preview.getByRole('checkbox').check();await preview.getByRole('button',{name:'Approve reversal'}).click();
 await expect(page.getByText('Correction revision 2',{exact:true})).toBeVisible();
 expect((await (await request.get(base+'/dashboard')).json()).revenue[0].amount).toBe('14.00');
 expect(await (await request.get(base+'/workbooks/'+book.id+'/download')).body()).toEqual(content);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
